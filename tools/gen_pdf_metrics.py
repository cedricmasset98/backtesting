"""Generate src/ui/pdfmetrics.ts: glyph widths of the PDF standard fonts Helvetica
and Helvetica-Bold for the 256 codes of WinAnsiEncoding (cp1252), read from the
Adobe Font Metrics files (Adobe Core14 AFM, freely redistributable).

    python tools/gen_pdf_metrics.py <dir with Helvetica.afm and Helvetica-Bold.afm>
"""
import sys
from pathlib import Path

from fontTools.agl import UV2AGL


def widths(afm: Path) -> list[int]:
    by_name = {}
    for line in afm.read_text(encoding="latin-1").splitlines():
        if line.startswith("C "):
            parts = dict(p.strip().split(" ", 1) for p in line.split(";") if p.strip() and " " in p.strip())
            by_name[parts["N"]] = int(float(parts["WX"]))
    out = []
    for code in range(256):
        try:
            ch = bytes([code]).decode("cp1252")
        except UnicodeDecodeError:
            out.append(0)
            continue
        name = UV2AGL.get(ord(ch), "space" if code == 160 else None)
        if code == 173:
            name = "hyphen"
        out.append(by_name.get(name, 0) if name else 0)
    return out


d = Path(sys.argv[1])
reg, bold = widths(d / "Helvetica.afm"), widths(d / "Helvetica-Bold.afm")
src = (
    "// Generated by tools/gen_pdf_metrics.py from the Adobe Core14 AFM files (Helvetica, Helvetica-Bold).\n"
    "// Advance widths in 1/1000 em for WinAnsiEncoding (cp1252) codes 0-255; 0 = no glyph.\n"
    f"export const HELVETICA: number[] = {reg};\n"
    f"export const HELVETICA_BOLD: number[] = {bold};\n"
)
Path("src/ui/pdfmetrics.ts").write_text(src)
print("ok", reg[65], bold[65], reg[233], reg[150])
